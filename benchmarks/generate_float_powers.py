"""Generate/check fixed-point multipliers using Python's exact integers.

No reference formatter or third-party package participates in generation.
Run with --write after changing the mathematical definition; CI only checks.
"""

import argparse
from pathlib import Path

DESTINATION = Path(__file__).resolve().parents[1] / "nextjson/src/float/powers.rs"


def table(bits, bias, maximum, digits):
    rows = []
    for raw in range(1, maximum):
        order2 = raw - bias
        order10 = (len(str(1 << order2)) - 1 if order2 >= 0
                   else -len(str(1 << -order2)))
        places = digits - 1 - order10
        binary = order2 - bits + 68
        numerator = (1 << max(binary, 0)) * 10 ** max(places, 0)
        denominator = (1 << max(-binary, 0)) * 10 ** max(-places, 0)
        factor, remainder = divmod(numerator, denominator)
        assert factor * denominator <= numerator < (factor + 1) * denominator
        # Largest upper boundary product, including approximation error.
        assert ((1 << (bits + 3)) - 2) * (factor + 1) < 1 << 128
        # Unique-candidate spacing used by decimal::convert.
        assert 4 * (factor + 1) < (100 if bits == 52 else 1000) * (1 << 70)
        assert factor >> 64 < 1 << 16
        rows.append(f"    Power {{ low: {factor % (1 << 64)}, high: {factor >> 64}, places: {places}, exact: {str(remainder == 0).lower()} }},")
    return rows


def generated_source():
    lines = [
        "// Generated by benchmarks/generate_float_powers.py; do not edit by hand.",
        "// factor = floor(2^(raw - bias - bits + 68) * 10^places).",
        "// exact records whether the expression is an integer.",
        "use super::Power;",
    ]
    for name, bits, bias, maximum, digits in [
        ("BINARY64", 52, 1023, 2047, 17), ("BINARY32", 23, 127, 255, 9)
    ]:
        lines += ["", "#[rustfmt::skip]", f"pub(super) static {name}: [Power; {maximum - 1}] = ["]
        lines += table(bits, bias, maximum, digits)
        lines += ["];"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    options = parser.parse_args()
    expected = generated_source()
    if options.write:
        DESTINATION.write_text(expected, encoding="utf-8", newline="\n")
    else:
        actual = DESTINATION.read_text(encoding="utf-8")
        if actual != expected:
            raise SystemExit("float power table differs from its exact integer definition")
    print("verified 2300 fixed-point multipliers and their u128 bounds")


if __name__ == "__main__":
    main()
